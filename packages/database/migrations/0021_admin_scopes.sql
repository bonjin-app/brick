-- 운영자 권한 범위 — "이 운영자는 주문만"
--
-- 운영자(manager)는 플러그인의 관리 화면 전부에 닿았다. 대행사·가게는 흔히 "택배 담당은
-- 주문만, 고객센터는 문의만" 을 원하는데, 역할이 세 단계(관리자·운영자·회원)뿐이라 방법이
-- 없었다 — 주문만 맡길 사람에게 상품 가격과 쿠폰을 바꿀 권한까지 줘야 했다.
--
