--
-- 필수/선택은 `is_required` 열이 들고 있는 사실이고, 화면이 그것을 보여준다.
-- 제목은 무엇에 동의하는지만 말하면 된다.
--
-- 운영자가 제목을 직접 고쳤을 수 있으므로 **원래 문구일 때만** 바꾼다.
UPDATE agreements
SET title = '광고성 정보 수신 동의'
WHERE kind = 'marketing' AND title = '광고성 정보 수신 동의 (선택)';
