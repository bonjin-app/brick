-- 예약 발행
--
-- `published_at` 은 지금까지 **"발행한 순간"** 을 적는 칸이었다. 그래서 공지·이벤트
-- 페이지를 정해진 시각에 여는 방법이 없었고, 운영자가 그 시각에 깨어 있어야 했다
-- (새벽 0시 공개라면 새벽 0시에). 워드프레스가 20년 전부터 가진 기능이다.
--
-- 상태에 `scheduled` 를 더한다. 뜻: **`published_at` 이 되면 공개한다.**
-- 그때까지는 `published` 가 아니므로 손님·검색·사이트맵 어디에도 나오지 않는다 —
-- 공개 여부를 판단하는 곳이 이미 전부 `status = 'published'` 하나를 본다.
--
-- 열거형(enum)으로 바꾸지 않는다. 상태를 더할 때마다 마이그레이션으로 타입을
-- 고쳐야 하고, 그 잠금은 큰 테이블에서 위험하다. 대신 들어오는 값은 컨트롤러가 막는다.

-- 때가 된 것을 찾는 질의는 30초마다 돈다 — 예약된 행만 보는 부분 인덱스로 둔다.
-- 예약이 하나도 없는 사이트(대부분)에서 이 인덱스는 비어 있다.
CREATE INDEX IF NOT EXISTS pages_scheduled_idx
  ON pages (published_at) WHERE status = 'scheduled';
